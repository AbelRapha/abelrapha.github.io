function detectLang() {
    const saved = localStorage.getItem("lang");
    if (LANGS.includes(saved)) return saved;
    const browser = (navigator.language || "pt").slice(0, 2).toLowerCase();
    return LANGS.includes(browser) ? browser : "pt";
}

let currentLang = detectLang();

function t(key) {
    const dict = I18N[currentLang] || {};
    return dict[key] !== undefined ? dict[key] : (I18N.pt[key] || "");
}

function applyLang(lang) {
    currentLang = LANGS.includes(lang) ? lang : "pt";
    localStorage.setItem("lang", currentLang);
    document.documentElement.lang = HTML_LANG[currentLang];

    document.querySelectorAll("[data-i18n]").forEach((el) => {
        el.textContent = t(el.dataset.i18n);
    });

    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
        el.innerHTML = t(el.dataset.i18nHtml);
    });

    document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
        el.dataset.i18nAttr.split(";").forEach((pair) => {
            const [attr, key] = pair.split(":").map((s) => s.trim());
            if (attr && key) el.setAttribute(attr, t(key));
        });
    });

    document.querySelectorAll("[data-lang-option]").forEach((btn) => {
        btn.setAttribute("aria-pressed", String(btn.dataset.langOption === currentLang));
    });

    document.dispatchEvent(new CustomEvent("langchange", { detail: { lang: currentLang } }));
}

function buildLangSwitch() {
    document.querySelectorAll("[data-lang-switch]").forEach((box) => {
        box.setAttribute("role", "group");
        box.innerHTML = LANGS.map((code) =>
            `<button type="button" class="lang-switch__btn" data-lang-option="${code}" aria-pressed="false" title="${LANG_CODES[code]}">` +
            `${FLAG_SVG[code]}<span class="lang-switch__code">${LANG_CODES[code]}</span></button>`
        ).join("");
    });

    document.querySelectorAll("[data-lang-option]").forEach((btn) => {
        btn.addEventListener("click", () => applyLang(btn.dataset.langOption));
    });
}

document.addEventListener("DOMContentLoaded", () => {
    buildLangSwitch();
    applyLang(currentLang);
});
